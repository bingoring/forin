// 사다리의 두 회차 가운데 **가이드 회차**를 가리키는 값.
//
// 2026-09-30에 `choices` 에서 `guided` 로 이름이 바뀌었다. v44가 보기 3개를 폐기하고
// 한국어 목표 문장 하나를 주는 방식으로 바꾸면서, 고를 것이 없어졌기 때문이다.
export const GUIDED = 'guided';

// 옛 이름. 딥링크(`?guide=choices`)에 박혀 남의 기록과 알림에 살아 있고, 서버에도
// 그 이름으로 저장된 진도 행이 있다. **읽을 때만** 받는다 — 새로 보내지는 않는다.
const LEGACY_GUIDED = 'choices';

/**
 * 받은 값이 가이드 회차를 뜻하는지 본다.
 *
 * 이 규칙이 한 곳에 있는 이유가 있다. 앱이 여러 자리에서 `=== 'choices'` 로 직접
 * 견주고 있었고, 서버가 `guided` 를 보내기 시작하면 그 비교가 전부 조용히 거짓이 된다.
 * 화면은 멀쩡히 그려지는데 **가이드 회차가 자유 회차로 나온다** — 보기도 힌트도 없이
 * 빈 칸만 서고, 학습자는 안내받을 차례에 혼자 던져진다. 터지지 않는 종류의 고장이라
 * 눈으로 찾기 어렵다.
 */
export function isGuidedRung(v: string | null | undefined): boolean {
  return v === GUIDED || v === LEGACY_GUIDED;
}
