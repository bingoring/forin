d=yaml.safe_load(open('icu-liver-failure.yaml'))
S=d['situations']
strip=r'(은|는|이|가|을|를|에|에서|에게|께|와|과|도|로|으로|의|만|까지|부터|요|이에요|예요|해요)$'
cnt=collections.Counter();where=collections.defaultdict(list)
bad=[]
for i,s in enumerate(S):
  for j,t in enumerate(s['sentences']):
    k=f'{i}.{j}'; dk=list(t['distractorsKo'])
    if k in P:
      for n,v in enumerate(P[k]):
        if v: dk[n]=v
    ko=t['ko']
    for x in dk:
      a,b=len(re.sub(r'\s','',ko)),len(re.sub(r'\s','',x))
      if max(a,b)/min(a,b)>1.25 and abs(a-b)>3: bad.append((k,'V20',x,b,a))
    L=lambda z:len(re.sub(r'\s','',z))
    if min(L(x) for x in dk)>L(ko): bad.append((k,'둘 다 김',[L(x) for x in dk],L(ko),'바꿈' if k in P else '원래'))
    kow=set(re.sub(strip,'',w) for w in re.findall(r'[가-힣A-Za-z0-9]+',ko)); raw=set(re.findall(r'[가-힣A-Za-z0-9]+',ko))
    for x in dk:
      for w in set(re.findall(r'[가-힣A-Za-z0-9]+',x)):
        if w in raw: continue
        st=re.sub(strip,'',w)
        if st in kow: continue
        stem=st[:2]; cnt[stem]+=1; where[stem].append(f'{k}:{w}')
print('길이 문제:',bad)
for w,c in cnt.most_common():
  if c>=5: print(c,w,where[w])
