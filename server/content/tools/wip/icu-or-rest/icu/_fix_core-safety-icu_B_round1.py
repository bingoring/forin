fs = {f: open(f, encoding="utf-8").read() for f in sorted(glob.glob("addB_core-safety-icu_*.yaml"))}
def rep(old, new, count=1):
    for f, t in fs.items():
        if old in t:
            fs[f] = t.replace(old, new, count); return
    raise SystemExit("NOT FOUND: " + old)
for old, new in R:
    if old == new or new == 'XX' or old.endswith('XX'): continue
    rep(old, new)
for f, t in fs.items(): open(f, "w", encoding="utf-8").write(t)
print("ok")
