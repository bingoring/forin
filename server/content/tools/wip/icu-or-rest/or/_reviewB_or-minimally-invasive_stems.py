for si,s in enumerate(d['situations']):
  for j,x in enumerate(s['sentences']):
    for k,dk in enumerate(x['distractorsKo']):
      for g,p in G.items():
        if re.search(p,' '+dk+' ') and not re.search(p,' '+x['ko']+' '): C[g]+=1; W[g].append(f'{si}.{j}.{k}')
