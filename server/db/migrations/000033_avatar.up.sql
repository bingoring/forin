-- 프로필 초상화 — NbAvatar 스펙 (핸드오프 v32).
--
-- 열 축(피부·머리·머리색·눈·입·옷·옷색·모자·배경·액세서리)의 키 조합이다.
-- 컬럼 열 개가 아니라 jsonb 하나로 두는 이유:
--
--  1. 축이 늘어난다. v32가 열 축이고, 다음 핸드오프에 수염이 붙으면 컬럼 하나가
--     아니라 마이그레이션 하나가 필요해진다.
--  2. 서버는 이 값을 해석하지 않는다. 그릴 수 있는지는 클라가 아는 일이고,
--     서버가 하는 일은 허용 키인지 확인하고(internal/domain/avatar) 돌려주는
--     것뿐이다.
--
-- NULL은 "고른 적 없음"이고 지운 값이 아니다. 그때 클라는 user id에서 파생한
-- 얼굴을 그린다 — 가입 시 쓰기 없이 모든 계정이 첫 순간부터 얼굴을 갖고,
-- 기기가 달라도 같은 얼굴이 나온다. 그래서 기존 사용자 백필도 필요 없다.
ALTER TABLE profiles ADD COLUMN avatar jsonb;
